/**
 * Applies watermark and footers to all pages
 */
export const applyWatermarkToAllPages = (doc: jsPDF) => {
  const totalPages = (doc as any).internal.getNumberOfPages();

  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);

    // Add watermark
    addWatermark(doc);

    // Add footer
    addUnMessFooter(doc, i);
  }
};

